#!/usr/bin/env python3
"""单文件 Token 上限检查（默认 5,000 Tokens = 20,000 Bytes）。

只依赖 Python 标准库。
- 默认（--staged）：检查暂存区中本次修改/新增的 .kt 文件（增量）；
- --all：检查整个工作区所有已跟踪的 .kt 文件（全量）；
- --stat：输出按模块统计的超标文件大盘。

自动忽略非 Agent 产出物（libs 目录、ViewBinding、Room _Impl、Navigation Directions、
头部带有 @generated / DO NOT EDIT 标记的生成代码等）。
支持 // githooks:ignore-file file-token-limit 显式放行。
"""

from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys
from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path

# --------------------------------------------------------------------------
# 策略常量
# --------------------------------------------------------------------------

TOKEN_LIMIT = 5000
BYTES_PER_TOKEN = 4
BYTE_LIMIT = TOKEN_LIMIT * BYTES_PER_TOKEN  # 20,000 Bytes

TARGET_SUFFIX = ".kt"

EXCLUDE_PREFIXES = (
    "libs/",
    "build/",
    ".gradle/",
)

# 典型由工具/插件生成的 Kotlin 代码文件名模式
CODEGEN_NAME_PATTERNS = re.compile(
    r"(?:Binding|Directions|_Impl|\.generated|__generated__|_pb2|\.pb)\.kt$"
    r"|^BuildConfig\.kt$|^R\.kt$",
    re.IGNORECASE,
)

# 代码生成器常在文件头部输出的标记（忽略大小写检测）
CODEGEN_HEADER_MARKERS = (
    "@generated",
    "do not edit",
    "code generated by",
    "autogenerated by",
    "this file is automatically generated",
    "generated by the protocol buffer compiler",
)

# 放行指令：写在文件任意位置（推荐首部）
IGNORE_DIRECTIVE = re.compile(r"githooks:ignore(-file)?\s+([\w,\-]+)")
RULE_NAME = "file-token-limit"


@dataclass(frozen=True)
class Violation:
    path: str
    bytes_size: int
    tokens: int
    excess_tokens: int


# --------------------------------------------------------------------------
# 纯函数判定逻辑（便于单元测试覆盖）
# --------------------------------------------------------------------------


def calculate_tokens(bytes_size: int) -> int:
    """按 Tokens = bytes / 4 估算 token 数量。"""
    return max(0, bytes_size) // BYTES_PER_TOKEN


def is_excluded_prefix(path: str, prefixes: tuple[str, ...] = EXCLUDE_PREFIXES) -> bool:
    """检查是否属于排除路径（如第三方库 libs/、构建产物 build/）。"""
    return any(path.startswith(prefix) for prefix in prefixes)


def is_codegen_filename(path: str) -> bool:
    """根据文件名命名特征判断是否为生成文件。"""
    filename = Path(path).name
    return CODEGEN_NAME_PATTERNS.search(filename) is not None


def is_codegen_header(header_snippet: str) -> bool:
    """检查文件头部片段是否包含生成代码标记。"""
    lower = header_snippet.lower()
    return any(marker in lower for marker in CODEGEN_HEADER_MARKERS)


def is_ignored_file(content: str, rule: str = RULE_NAME) -> bool:
    """检查文件内是否声明了针对该规则或 all 的放行标记。"""
    for line in content.splitlines():
        match = IGNORE_DIRECTIVE.search(line)
        if match:
            directives = {d.strip() for d in match.group(2).split(",") if d.strip()}
            if rule in directives or "all" in directives:
                return True
    return False


def format_violation_report(violations: list[Violation]) -> str:
    """生成格式化的拦截报错信息与分场景拆解操作指引。"""
    lines = [
        "",
        "================================================================================",
        f"❌ [GITHOOKS] 提交被拦截：检测到 {len(violations)} 个文件超出 {TOKEN_LIMIT:,} Tokens 限制 (上限 {BYTE_LIMIT:,} Bytes)",
        "================================================================================",
        "",
        "【超标文件明细】",
    ]

    for v in sorted(violations, key=lambda x: -x.tokens):
        ratio = (v.tokens / TOKEN_LIMIT) * 100
        lines.append(
            f"  • {v.path}\n"
            f"    当前大小: {v.bytes_size:,} Bytes ({v.tokens:,} Tokens) ➔ "
            f"超标 +{v.excess_tokens:,} Tokens (超限 {ratio:.1f}%)"
        )

    lines.extend([
        "",
        "--------------------------------------------------------------------------------",
        "💡 为什么限制 5,000 Tokens？",
        "  1. 保护模型注意力：单文件超长会导致 AI Agent 读写时丢失上下文，出现幻觉或工具截断；",
        "  2. 降低合并冲突：细粒度小文件显著减少多分支并发编辑时的冲突与爆炸半径；",
        "  3. 践行单一职责：倒逼按领域边界进行合理拆分与解耦。",
        "",
        "--------------------------------------------------------------------------------",
        "🛠️ 分场景拆分实操指引 (Step-by-Step Splitting Recipes)：",
        "",
        "  1. UI / Jetpack Compose 页面拆解：",
        "     • [抽离子组件] 将主页面中的局部布局独立为同级组件（如 *Header.kt, *List.kt, *Dialog.kt）；",
        "     • [拆分 Previews] 将 @Preview 组合函数统一迁移到独立的 *Previews.kt；",
        "     • [剥离样式配置] 将页面特定的配色、尺寸常数或动画规格抽出至 *Constants.kt。",
        "",
        "  2. ViewModel / 业务逻辑层拆解：",
        "     • [契约与状态下沉] 将 State、Event、Intent 独立到 *Contract.kt 或 *State.kt；",
        "     • [领域服务委托] 将非核心辅助业务（权限检查、数据格式化、埋点等）下沉至独立 Domain Service / UseCase；",
        "     • [工具扩展外置] 将私有数据变换辅助方法提取为顶层扩展函数放到 *Extensions.kt。",
        "",
        "  3. Repository / Service 数据分层拆解：",
        "     • [按领域生命周期拆分] 避免 Monolithic 大类，按业务实体分为子 Repo（如 AuthRepo, SyncRepo）；",
        "     • [DTO / 数据模型剥离] 将网络传输对象与数据库 Entity 抽离至独立的 *Models.kt；",
        "     • [存储与 IO 解耦] 将底层 Cache 与本地持久化逻辑独立为专用 Storage Delegate。",
        "",
        "  4. 单元测试类拆解：",
        "     • [按测试场景分流] 拆分为 *HappyPathTest.kt、*ErrorHandlingTest.kt、*ConcurrentTest.kt；",
        "     • [共享测试夹具] 将冗长的 Mock 数据构造与 Fixture 抽取至公共 *TestFixtures.kt。",
        "",
        "--------------------------------------------------------------------------------",
        "⚠️ 特殊场景豁免方式（Escape Hatch）：",
        "若该文件确实无法拆分且确有必要保留单文件形态，可在该文件内（推荐第一行）添加放行标记：",
        f"    // githooks:ignore-file {RULE_NAME}",
        "================================================================================",
    ])
    return "\n".join(lines)


# --------------------------------------------------------------------------
# Git 暂存区与仓库交互
# --------------------------------------------------------------------------


def git_cmd(root: str, *args: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        ["git", "-C", root, *args],
        text=True,
        capture_output=True,
        check=False,
    )


def get_staged_candidates(root: str) -> list[str]:
    """获取暂存区新增、修改、重命名的 .kt 文件列表。"""
    res = git_cmd(
        root,
        "-c",
        "core.quotePath=false",
        "diff",
        "--cached",
        "--name-only",
        "--diff-filter=ACMR",
        "--",
        f"*{TARGET_SUFFIX}",
    )
    if res.returncode != 0 or not res.stdout.strip():
        return []
    return [p.strip() for p in res.stdout.splitlines() if p.strip()]


def get_staged_size(root: str, path: str) -> int:
    """直接从 Git 对象库查询暂存区对应文件的实际字节数。"""
    res = git_cmd(root, "cat-file", "-s", f":{path}")
    if res.returncode == 0 and res.stdout.strip().isdigit():
        return int(res.stdout.strip())
    return 0


def get_staged_head(root: str, path: str, max_lines: int = 20) -> str:
    """读取暂存区文件前部内容，用于检查 Codegen 标记与放行指令。"""
    res = git_cmd(root, "show", f":{path}")
    if res.returncode != 0:
        return ""
    lines = res.stdout.splitlines()[:max_lines]
    return "\n".join(lines)


def get_all_tracked_candidates(root: str, scope: list[str]) -> list[str]:
    """全量获取工作区已跟踪的 .kt 文件。"""
    res = git_cmd(root, "-c", "core.quotePath=false", "ls-files", "-z", f"*{TARGET_SUFFIX}")
    if res.returncode != 0:
        return []
    paths = []
    for p in res.stdout.split("\0"):
        if not p:
            continue
        if scope and not any(p.startswith(s) for s in scope):
            continue
        paths.append(p)
    return paths


# --------------------------------------------------------------------------
# 检查执行核心
# --------------------------------------------------------------------------


def inspect_candidates(
    root: str,
    paths: list[str],
    size_getter,
    content_getter,
) -> tuple[list[Violation], int]:
    """对候选路径列表执行过滤与 Token 检查。

    返回 (违规列表, 豁免/跳过数)。
    """
    violations: list[Violation] = []
    skipped = 0

    for path in paths:
        if is_excluded_prefix(path) or is_codegen_filename(path):
            skipped += 1
            continue

        size = size_getter(root, path)
        if size <= BYTE_LIMIT:
            continue

        head = content_getter(root, path)
        if is_codegen_header(head):
            skipped += 1
            continue

        if is_ignored_file(head):
            skipped += 1
            continue

        tokens = calculate_tokens(size)
        violations.append(
            Violation(
                path=path,
                bytes_size=size,
                tokens=tokens,
                excess_tokens=tokens - TOKEN_LIMIT,
            )
        )

    return violations, skipped


def print_stat(violations: list[Violation], total_scanned: int) -> int:
    """输出按模块统计的超标文件概览。"""
    per_module: dict[str, list[Violation]] = defaultdict(list)
    for v in violations:
        module = v.path.split("/")[0]
        per_module[module].append(v)

    width = max((len(m) for m in per_module), default=6)
    print(f"{'module':<{width}}  {'files':>5}  {'max_tokens':>10}  {'total_excess':>12}")
    print("-" * (width + 33))

    for module in sorted(per_module, key=lambda m: -len(per_module[m])):
        items = per_module[module]
        max_t = max(i.tokens for i in items)
        sum_excess = sum(i.excess_tokens for i in items)
        print(f"{module:<{width}}  {len(items):>5}  {max_t:>10,}  {sum_excess:>12,}")

    print()
    print(f"check_tokens: 扫描 {total_scanned} 个文件，共 {len(violations)} 个超标文件")
    return 0


# --------------------------------------------------------------------------
# 命令行入口
# --------------------------------------------------------------------------


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="check_tokens.py",
        description="单文件 Token 上限检查（5,000 Tokens = 20,000 Bytes）。",
    )
    parser.add_argument(
        "--all",
        action="store_true",
        help="检查整个工作区已跟踪的 .kt 文件（全量），可附加路径限制范围。",
    )
    parser.add_argument(
        "--staged",
        action="store_true",
        help="检查暂存区新增/修改的 .kt 文件（默认行为）。",
    )
    parser.add_argument(
        "--stat",
        action="store_true",
        help="按模块统计超标文件并输出大盘。",
    )
    parser.add_argument("scope", nargs="*", help="--all 时的路径前缀限制。")
    args = parser.parse_args(argv)

    root = git_cmd(str(Path.cwd()), "rev-parse", "--show-toplevel").stdout.strip()
    if not root:
        print("check_tokens: 不在 git 仓库内", file=sys.stderr)
        return 0

    if args.all:
        paths = get_all_tracked_candidates(root, args.scope)

        def fs_size(r: str, p: str) -> int:
            try:
                return Path(r, p).stat().st_size
            except OSError:
                return 0

        def fs_head(r: str, p: str) -> str:
            try:
                with open(Path(r, p), "r", encoding="utf-8", errors="replace") as f:
                    lines = [f.readline() for _ in range(20)]
                    return "".join(lines)
            except OSError:
                return ""

        violations, skipped = inspect_candidates(root, paths, fs_size, fs_head)
    else:
        paths = get_staged_candidates(root)
        violations, skipped = inspect_candidates(root, paths, get_staged_size, get_staged_head)

    if args.stat:
        return print_stat(violations, len(paths))

    if violations:
        print(format_violation_report(violations), file=sys.stderr)
        return 1

    return 0


if __name__ == "__main__":
    sys.exit(main())
