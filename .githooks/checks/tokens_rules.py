"""单文件 Token 上限与尺寸守护检查（保护模型注意力，降低代码冲突，践行单一职责）。

只依赖 Python 标准库。限制单文件上限为 5,000 Tokens（20,000 Bytes）。
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path
from typing import Callable

from core.ignore import is_file_ignored
from core.models import Category, CheckResult, Finding, Rule, Severity

TOKEN_LIMIT = 5000
BYTES_PER_TOKEN = 4
BYTE_LIMIT = TOKEN_LIMIT * BYTES_PER_TOKEN  # 20,000 Bytes

TARGET_SUFFIX = ".kt"

EXCLUDE_PREFIXES = (
    "libs/",
    "build/",
    ".gradle/",
)

CODEGEN_NAME_PATTERNS = re.compile(
    r"(?:Binding|Directions|_Impl|\.generated|__generated__|_pb2|\.pb)\.kt$"
    r"|^BuildConfig\.kt$|^R\.kt$",
    re.IGNORECASE,
)

CODEGEN_HEADER_MARKERS = (
    "@generated",
    "do not edit",
    "code generated by",
    "autogenerated by",
    "this file is automatically generated",
    "generated by the protocol buffer compiler",
)

RULE_NAME = "file-token-limit"

TOKEN_RULE = Rule(
    name=RULE_NAME,
    category=Category.ARCHITECTURE,
    severity=Severity.BLOCK,
    description=f"单文件超出 {TOKEN_LIMIT:,} Tokens 限制 (上限 {BYTE_LIMIT:,} Bytes)",
    hint=f"按领域职责合理拆分；确实无法拆解时在文件头部添加 // githooks:ignore-file {RULE_NAME}",
)


@dataclass(frozen=True)
class Violation:
    path: str
    bytes_size: int
    tokens: int
    excess_tokens: int


def calculate_tokens(bytes_size: int) -> int:
    """按 Tokens = bytes / 4 换算 token 数量。"""
    return max(0, bytes_size) // BYTES_PER_TOKEN


def is_excluded_prefix(path: str, prefixes: tuple[str, ...] = EXCLUDE_PREFIXES) -> bool:
    """检查是否属于排除路径（如第三方库 libs/、构建产物 build/）。"""
    return any(path.startswith(prefix) for prefix in prefixes)


def is_codegen_filename(path: str) -> bool:
    """根据文件名命名特征判断是否为生成文件。"""
    filename = Path(path).name
    return CODEGEN_NAME_PATTERNS.search(filename) is not None


def is_codegen_header(header_snippet: str) -> bool:
    """检查文件头部片段是否包含生成代码标记。"""
    lower = header_snippet.lower()
    return any(marker in lower for marker in CODEGEN_HEADER_MARKERS)


def format_splitting_recipes(violations: list[Violation]) -> str:
    """分场景拆解操作建议文本。"""
    lines = [
        "🛠️ 分场景拆分实操指引 (Step-by-Step Splitting Recipes)：",
        "  1. Compose UI 页面拆解：抽离子组件布局（*Header.kt, *List.kt）、迁移 @Preview 至 *Previews.kt",
        "  2. ViewModel / 逻辑层：契约/状态下沉至 *Contract.kt、领域服务委托下沉、扩展方法外置",
        "  3. Repository / Service：按领域子模块分拆、DTO/Entity 模型剥离、存储逻辑委托",
        "  4. 单元测试类：按测试用例场景分流（*HappyPathTest.kt 等）、提取共享测试夹具",
    ]
    return "\n".join(lines)


def print_stat(violations: list[Violation], total_scanned: int) -> int:
    """输出按模块统计的超标文件概览。"""
    from collections import defaultdict
    per_module: dict[str, list[Violation]] = defaultdict(list)
    for v in violations:
        module = v.path.split("/")[0]
        per_module[module].append(v)

    width = max((len(m) for m in per_module), default=6)
    print(f"{'module':<{width}}  {'files':>5}  {'max_tokens':>10}  {'total_excess':>12}")
    print("-" * (width + 33))

    for module in sorted(per_module, key=lambda m: -len(per_module[m])):
        items = per_module[module]
        max_t = max(i.tokens for i in items)
        sum_excess = sum(i.excess_tokens for i in items)
        print(f"{module:<{width}}  {len(items):>5}  {max_t:>10,}  {sum_excess:>12,}")

    print()
    print(f"check_tokens: 扫描 {total_scanned} 个文件，共 {len(violations)} 个超标文件")
    return 0


def check_token_limits(
    paths: list[str],
    size_getter: Callable[[str], int],
    content_getter: Callable[[str], str],
    active_rules: set[str] | None = None,
) -> CheckResult:
    """执行文件体积与 Token 上限检查。"""
    if active_rules is not None and RULE_NAME not in active_rules:
        return CheckResult(findings=[], ignored=0, scanned_count=len(paths))

    findings: list[Finding] = []
    violations: list[Violation] = []
    ignored_count = 0

    for path in paths:
        if is_excluded_prefix(path) or is_codegen_filename(path):
            ignored_count += 1
            continue

        size = size_getter(path)
        if size <= BYTE_LIMIT:
            continue

        head = content_getter(path)
        if is_codegen_header(head):
            ignored_count += 1
            continue

        if is_file_ignored(head, RULE_NAME):
            ignored_count += 1
            continue

        tokens = calculate_tokens(size)
        excess = tokens - TOKEN_LIMIT
        ratio = (tokens / TOKEN_LIMIT) * 100
        v = Violation(path, size, tokens, excess)
        violations.append(v)

        msg = (
            f"当前大小: {size:,} Bytes ({tokens:,} Tokens) ➔ "
            f"超标 +{excess:,} Tokens (超限 {ratio:.1f}%)"
        )
        findings.append(
            Finding(
                path=path,
                lineno=None,
                rule=TOKEN_RULE.name,
                category=TOKEN_RULE.category.value,
                severity=TOKEN_RULE.severity.value,
                message=msg,
                hint=TOKEN_RULE.hint,
            )
        )

    return CheckResult(
        findings=findings,
        ignored=ignored_count,
        scanned_count=len(paths),
    )
