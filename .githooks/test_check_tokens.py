class TokenCalculationBoundaryTest(unittest.TestCase):
    def test_zero_and_negative_bytes_handled(self):
        self.assertEqual(calculate_tokens(0), 0)
        self.assertEqual(calculate_tokens(-10), 0)

    def test_exact_threshold_boundary(self):
        # 20,000 字节 = 5,000 Tokens (合规最大值)
        self.assertEqual(calculate_tokens(20000), 5000)
        # 20,004 字节 = 5,001 Tokens (超标起始值)
        self.assertEqual(calculate_tokens(20004), 5001)


class CodegenFilteringTest(unittest.TestCase):
    def test_excluded_prefixes_recognized(self):
        self.assertTrue(is_excluded_prefix("libs/okia/RealAgentLoop.kt"))
        self.assertTrue(is_excluded_prefix("build/generated/source/Foo.kt"))
        self.assertFalse(is_excluded_prefix("app/src/main/java/Foo.kt"))

    def test_codegen_filenames_recognized(self):
        self.assertTrue(is_codegen_filename("FragmentHomeBinding.kt"))
        self.assertTrue(is_codegen_filename("HomeNavDirections.kt"))
        self.assertTrue(is_codegen_filename("AppDatabase_Impl.kt"))
        self.assertTrue(is_codegen_filename("Schema.generated.kt"))
        self.assertTrue(is_codegen_filename("BuildConfig.kt"))
        self.assertTrue(is_codegen_filename("R.kt"))

        # 正常业务文件不应被误判为生成文件
        self.assertFalse(is_codegen_filename("HomePageContent.kt"))
        self.assertFalse(is_codegen_filename("DirectionHelper.kt"))
        self.assertFalse(is_codegen_filename("BindingAdapter.kt"))

    def test_codegen_header_markers_recognized(self):
        self.assertTrue(is_codegen_header("// @generated by tool"))
        self.assertTrue(is_codegen_header("/* DO NOT EDIT - code generated by compiler */"))
        self.assertTrue(is_codegen_header("// This file is automatically generated"))
        self.assertFalse(is_codegen_header("package com.niki914.zafiro\n\nclass Foo"))


class IgnoreDirectiveTest(unittest.TestCase):
    def test_honors_file_token_limit_ignore_marker(self):
        content = "// githooks:ignore-file file-token-limit\nclass HugeClass"
        self.assertTrue(is_ignored_file(content))

    def test_honors_all_ignore_marker(self):
        content = "// githooks:ignore-file all\nclass HugeClass"
        self.assertTrue(is_ignored_file(content))

    def test_does_not_leak_other_rules_ignore_marker(self):
        content = "// githooks:ignore-file monitor-lock,log-api\nclass HugeClass"
        self.assertFalse(is_ignored_file(content))


class InspectCandidatesFlowTest(unittest.TestCase):
    def test_filtering_pipeline_end_to_end(self):
        files_size = {
            "app/Normal.kt": 10000,                  # 合规 (< 20000)
            "app/Huge.kt": 30000,                    # 超标 (7500 tokens)
            "app/HugeIgnored.kt": 30000,             # 超标但有 ignore-file 标记
            "app/HugeBinding.kt": 30000,             # 超标但是 Binding 生成文件
            "app/HugeGeneratedHeader.kt": 30000,     # 超标但头部有 @generated 标记
            "libs/ThirdPartyHuge.kt": 40000,         # 超标但在 libs 排除路径
        }

        files_content = {
            "app/Normal.kt": "class Normal",
            "app/Huge.kt": "class Huge",
            "app/HugeIgnored.kt": "// githooks:ignore-file file-token-limit\nclass HugeIgnored",
            "app/HugeBinding.kt": "class HugeBinding",
            "app/HugeGeneratedHeader.kt": "// @generated\nclass HugeGenerated",
            "libs/ThirdPartyHuge.kt": "class ThirdParty",
        }

        violations, skipped = inspect_candidates(
            root="/mock",
            paths=list(files_size.keys()),
            size_getter=lambda r, p: files_size.get(p, 0),
            content_getter=lambda r, p: files_content.get(p, ""),
        )

        # 仅 app/Huge.kt 违规
        self.assertEqual(len(violations), 1)
        self.assertEqual(violations[0].path, "app/Huge.kt")
        self.assertEqual(violations[0].bytes_size, 30000)
        self.assertEqual(violations[0].tokens, 7500)
        self.assertEqual(violations[0].excess_tokens, 2500)
        self.assertEqual(skipped, 4)


class ViolationReportFormatTest(unittest.TestCase):
    def test_report_contains_metrics_and_instructions(self):
        v = Violation(
            path="app/Huge.kt",
            bytes_size=28000,
            tokens=7000,
            excess_tokens=2000,
        )
        report = format_violation_report([v])

        # 验证量化指标
        self.assertIn("app/Huge.kt", report)
        self.assertIn("28,000 Bytes", report)
        self.assertIn("7,000 Tokens", report)
        self.assertIn("+2,000 Tokens", report)

        # 验证场景化拆解指引
        self.assertIn("Compose", report)
        self.assertIn("ViewModel", report)
        self.assertIn("Repository", report)
        self.assertIn("单元测试", report)

        # 验证豁免提示
        self.assertIn("// githooks:ignore-file file-token-limit", report)


